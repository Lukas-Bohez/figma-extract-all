// Builds the OWNER variant of the plugin: code.owner.js (+ manifest.owner.json is already in the repo).
//
//   npm run build:owner                       makes a key for you on the first run and keeps it in ~/.figma-extract-all/owner-key
//   FIGMA_OWNER_KEY=<a secret of at least 16 characters> npm run build:owner
//   node build-owner.mjs --out some/other/place.js       (tests use this, with a throw-away key)
//
// The key is written to owner.key.ts (gitignored), compiled into the output, removed again and never printed. The same key in
// FIGMA_OWNER_KEY (or the key file) on the machine that runs the bridge is what makes the owner commands work.
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OWNER_KEY_FILE, readOwnerKey } from './bridge/src/owner.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const outAt = process.argv.indexOf('--out');
const out = outAt > 0 ? process.argv[outAt + 1] : null;

// The key: FIGMA_OWNER_KEY, else the key file of this computer, else a new random one that is saved in that file.
// With --out (the tests) and no key in the environment nothing is invented or saved: the build just refuses.
const fromEnv = (process.env.FIGMA_OWNER_KEY || '').trim();
let key = fromEnv || readOwnerKey({}) || '';
if (!key && !out) {
  key = randomBytes(24).toString('hex');
  mkdirSync(dirname(OWNER_KEY_FILE), { recursive: true });
  writeFileSync(OWNER_KEY_FILE, `${key}\n`);
  console.log(`Nieuwe eigenaarssleutel gemaakt en bewaard in ${OWNER_KEY_FILE}. Deel hem met niemand.`);
}
if (key.length < 16) {
  console.error('FIGMA_OWNER_KEY ontbreekt of is korter dan 16 tekens. Kies een eigen geheim of laat `npm run build:owner` er een maken.');
  process.exit(1);
}

writeFileSync(join(root, 'owner.key.ts'), `// Generated by build-owner.mjs. Gitignored. Never commit this file.\nconst OWNER_KEY: string = ${JSON.stringify(key)};\n`);

// tsc is run through node itself (no shell), so paths with spaces in them work on Windows
const args = [join(root, 'node_modules', 'typescript', 'lib', 'tsc.js'), '-p', 'tsconfig.owner.json'];
if (out) args.push('--outFile', out);
const run = spawnSync(process.execPath, args, { cwd: root, stdio: 'inherit' });
// The key is now inside the output; the source file with it does not stay on disk
rmSync(join(root, 'owner.key.ts'), { force: true });
if (run.status !== 0) process.exit(run.status ?? 1);
console.log(out ? `Owner build: ${out}` : 'Owner build: code.owner.js. In Figma: Plugins → Development → Import plugin from manifest → manifest.owner.json');
